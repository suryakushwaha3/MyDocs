@Composable
fun AiFeaturesScreen(
    onBackClick: () -> Unit = {}
) {
    var isAutoSummaryEnabled by remember { mutableStateOf(true) }
    var isSmartSearchEnabled by remember { mutableStateOf(true) }
    var isAutoTaggingEnabled by remember { mutableStateOf(true) }
    var aiModelQuality by remember { mutableStateOf("Balanced (Recommended)") }

    Column(
        modifier = Modifier
            .fillMaxSize()
            .background(Color(0xFFF8F9FA))
    ) {
        // Top App Bar
        Surface(
            modifier = Modifier.fillMaxWidth(),
            color = Color.White,
            shadowElevation = 1.dp
        ) {
            Row(
                modifier = Modifier
                    .fillMaxWidth()
                    .padding(horizontal = 16.dp, vertical = 12.dp),
                verticalAlignment = Alignment.CenterVertically
            ) {
                IconButton(onClick = onBackClick) {
                    Icon(
                        imageVector = Icons.Default.ArrowBack,
                        contentDescription = "Back",
                        tint = Color(0xFF1E1E24)
                    )
                }
                Spacer(modifier = Modifier.width(8.dp))
                Text(
                    text = "AI Features & Intelligence",
                    fontWeight = FontWeight.Bold,
                    fontSize = 20.sp,
                    color = Color(0xFF1E1E24)
                )
            }
        }

        LazyColumn(
            modifier = Modifier
                .fillMaxWidth()
                .weight(1f)
                .padding(horizontal = 20.dp),
            verticalArrangement = Arrangement.spacedBy(16.dp),
            contentPadding = PaddingValues(vertical = 20.dp)
        ) {
            // SMART AUTOMATION SECTION
            item {
                Text(
                    text = "SMART AUTOMATION",
                    fontSize = 12.sp,
                    fontWeight = FontWeight.Bold,
                    color = Color.Gray,
                    modifier = Modifier.padding(start = 4.dp, top = 4.dp, bottom = 2.dp)
                )
            }
            item {
                Surface(
                    modifier = Modifier.fillMaxWidth(),
                    shape = RoundedCornerShape(16.dp),
                    color = Color.White,
                    shadowElevation = 1.dp
                ) {
                    Column(modifier = Modifier.fillMaxWidth()) {
                        AiSwitchItem(
                            icon = Icons.Default.AutoAwesome,
                            title = "Auto-Summarize Documents",
                            subtitle = "Generate quick bullet-point summaries for long PDFs",
                            checked = isAutoSummaryEnabled,
                            onCheckedChange = { isAutoSummaryEnabled = it }
                        )
                        AiDivider()
                        AiSwitchItem(
                            icon = Icons.Default.Label,
                            title = "Smart Auto-Tagging",
                            subtitle = "Automatically categorize and tag documents using AI",
                            checked = isAutoTaggingEnabled,
                            onCheckedChange = { isAutoTaggingEnabled = it }
                        )
                    }
                }
            }

            // SEARCH & RETRIEVAL SECTION
            item {
                Text(
                    text = "SEARCH & RETRIEVAL",
                    fontSize = 12.sp,
                    fontWeight = FontWeight.Bold,
                    color = Color.Gray,
                    modifier = Modifier.padding(start = 4.dp, top = 8.dp, bottom = 2.dp)
                )
            }
            item {
                Surface(
                    modifier = Modifier.fillMaxWidth(),
                    shape = RoundedCornerShape(16.dp),
                    color = Color.White,
                    shadowElevation = 1.dp
                ) {
                    Column(modifier = Modifier.fillMaxWidth()) {
                        AiSwitchItem(
                            icon = Icons.Default.TravelExplore,
                            title = "Semantic Smart Search",
                            subtitle = "Search files using natural queries and context",
                            checked = isSmartSearchEnabled,
                            onCheckedChange = { isSmartSearchEnabled = it }
                        )
                        AiDivider()
                        AiClickableItem(
                            icon = Icons.Default.Translate,
                            title = "Default AI Translation Language",
                            subtitle = "English (Auto-detect source)",
                            onClick = { /* Handle translation language selection */ }
                        )
                    }
                }
            }

            // MODEL PREFERENCES SECTION
            item {
                Text(
                    text = "MODEL PREFERENCES",
                    fontSize = 12.sp,
                    fontWeight = FontWeight.Bold,
                    color = Color.Gray,
                    modifier = Modifier.padding(start = 4.dp, top = 8.dp, bottom = 2.dp)
                )
            }
            item {
                Surface(
                    modifier = Modifier.fillMaxWidth(),
                    shape = RoundedCornerShape(16.dp),
                    color = Color.White,
                    shadowElevation = 1.dp
                ) {
                    Column(modifier = Modifier.fillMaxWidth()) {
                        AiClickableItem(
                            icon = Icons.Default.Psychology,
                            title = "AI Engine & Performance",
                            subtitle = aiModelQuality,
                            onClick = {
                                aiModelQuality = if (aiModelQuality.contains("Balanced"))
                                    "High Accuracy (Slower)"
                                else
                                    "Balanced (Recommended)"
                            }
                        )
                        AiDivider()
                        AiClickableItem(
                            icon = Icons.Default.DataUsage,
                            title = "Local AI Data Processing",
                            subtitle = "Keep data processing on-device for maximum privacy",
                            onClick = { /* Handle on-device toggle info */ }
                        )
                    }
                }
                Spacer(modifier = Modifier.height(20.dp))
            }
        }
    }
}

@Composable
fun AiSwitchItem(
    icon: ImageVector,
    title: String,
    subtitle: String,
    checked: Boolean,
    onCheckedChange: (Boolean) -> Unit
) {
    Row(
        modifier = Modifier
            .fillMaxWidth()
            .padding(horizontal = 16.dp, vertical = 12.dp),
        horizontalArrangement = Arrangement.SpaceBetween,
        verticalAlignment = Alignment.CenterVertically
    ) {
        Row(
            verticalAlignment = Alignment.CenterVertically,
            modifier = Modifier.weight(1f)
        ) {
            Box(
                modifier = Modifier
                    .size(40.dp)
                    .clip(CircleShape)
                    .background(Color(0xFF3B59FF).copy(alpha = 0.1f)),
                contentAlignment = Alignment.Center
            ) {
                Icon(
                    imageVector = icon,
                    contentDescription = null,
                    tint = Color(0xFF3B59FF),
                    modifier = Modifier.size(20.dp)
                )
            }
            Spacer(modifier = Modifier.width(14.dp))
            Column {
                Text(
                    text = title,
                    fontSize = 14.sp,
                    fontWeight = FontWeight.Medium,
                    color = Color(0xFF1E1E24)
                )
                Spacer(modifier = Modifier.height(2.dp))
                Text(
                    text = subtitle,
                    fontSize = 11.5.sp,
                    color = Color.Gray
                )
            }
        }
        Switch(
            checked = checked,
            onCheckedChange = onCheckedChange,
            colors = SwitchDefaults.colors(
                checkedThumbColor = Color.White,
                checkedTrackColor = Color(0xFF3B59FF)
            )
        )
    }
}

