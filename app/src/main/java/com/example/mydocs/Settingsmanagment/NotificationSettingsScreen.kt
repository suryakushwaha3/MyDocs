@Composable
fun NotificationSettingsScreen(
    onBackClick: () -> Unit = {}
) {
    var isPushEnabled by remember { mutableStateOf(true) }
    var isExpiryAlertsEnabled by remember { mutableStateOf(true) }
    var isSecurityAlertsEnabled by remember { mutableStateOf(true) }
    var isDailyDigestEnabled by remember { mutableStateOf(false) }

    Column(
        modifier = Modifier
            .fillMaxSize()
            .background(Color(0xFFF8F9FA))
    ) {
        // Top App Bar
        Surface(
            modifier = Modifier.fillMaxWidth(),
            color = Color.White,
            shadowElevation = 1.dp
        ) {
            Row(
                modifier = Modifier
                    .fillMaxWidth()
                    .padding(horizontal = 16.dp, vertical = 12.dp),
                verticalAlignment = Alignment.CenterVertically
            ) {
                IconButton(onClick = onBackClick) {
                    Icon(
                        imageVector = Icons.Default.ArrowBack,
                        contentDescription = "Back",
                        tint = Color(0xFF1E1E24)
                    )
                }
                Spacer(modifier = Modifier.width(8.dp))
                Text(
                    text = "Notification Settings",
                    fontWeight = FontWeight.Bold,
                    fontSize = 20.sp,
                    color = Color(0xFF1E1E24)
                )
            }
        }

        LazyColumn(
            modifier = Modifier
                .fillMaxWidth()
                .weight(1f)
                .padding(horizontal = 20.dp),
            verticalArrangement = Arrangement.spacedBy(16.dp),
            contentPadding = PaddingValues(vertical = 20.dp)
        ) {
            // GENERAL NOTIFICATIONS SECTION
            item {
                Text(
                    text = "GENERAL NOTIFICATIONS",
                    fontSize = 12.sp,
                    fontWeight = FontWeight.Bold,
                    color = Color.Gray,
                    modifier = Modifier.padding(start = 4.dp, top = 4.dp, bottom = 2.dp)
                )
            }
            item {
                Surface(
                    modifier = Modifier.fillMaxWidth(),
                    shape = RoundedCornerShape(16.dp),
                    color = Color.White,
                    shadowElevation = 1.dp
                ) {
                    Column(modifier = Modifier.fillMaxWidth()) {
                        NotificationSwitchItem(
                            icon = Icons.Default.NotificationsActive,
                            title = "Push Notifications",
                            subtitle = "Receive instant alerts on your device",
                            checked = isPushEnabled,
                            onCheckedChange = { isPushEnabled = it }
                        )
                        NotificationDivider()
                        NotificationSwitchItem(
                            icon = Icons.Default.Email,
                            title = "Email Notifications",
                            subtitle = "Get important updates via registered email",
                            checked = false,
                            onCheckedChange = { /* Handle email toggle */ }
                        )
                    }
                }
            }

            // ALERTS & REMINDERS SECTION
            item {
                Text(
                    text = "ALERTS & REMINDERS",
                    fontSize = 12.sp,
                    fontWeight = FontWeight.Bold,
                    color = Color.Gray,
                    modifier = Modifier.padding(start = 4.dp, top = 8.dp, bottom = 2.dp)
                )
            }
            item {
                Surface(
                    modifier = Modifier.fillMaxWidth(),
                    shape = RoundedCornerShape(16.dp),
                    color = Color.White,
                    shadowElevation = 1.dp
                ) {
                    Column(modifier = Modifier.fillMaxWidth()) {
                        NotificationSwitchItem(
                            icon = Icons.Default.Timer,
                            title = "Document Expiry Alerts",
                            subtitle = "Remind me before IDs, licenses, or agreements expire",
                            checked = isExpiryAlertsEnabled,
                            onCheckedChange = { isExpiryAlertsEnabled = it }
                        )
                        NotificationDivider()
                        NotificationSwitchItem(
                            icon = Icons.Default.Security,
                            title = "Security & Sign-in Alerts",
                            subtitle = "Get notified of new logins or permission requests",
                            checked = isSecurityAlertsEnabled,
                            onCheckedChange = { isSecurityAlertsEnabled = it }
                        )
                        NotificationDivider()
                        NotificationSwitchItem(
                            icon = Icons.Default.ViewTimeline,
                            title = "Daily Summary Digest",
                            subtitle = "Receive a single daily roundup of document activities",
                            checked = isDailyDigestEnabled,
                            onCheckedChange = { isDailyDigestEnabled = it }
                        )
                    }
                }
            }

            // SOUND & VIBRATION SECTION
            item {
                Text(
                    text = "SOUND & VIBRATION",
                    fontSize = 12.sp,
                    fontWeight = FontWeight.Bold,
                    color = Color.Gray,
                    modifier = Modifier.padding(start = 4.dp, top = 8.dp, bottom = 2.dp)
                )
            }
            item {
                Surface(
                    modifier = Modifier.fillMaxWidth(),
                    shape = RoundedCornerShape(16.dp),
                    color = Color.White,
                    shadowElevation = 1.dp
                ) {
                    Column(modifier = Modifier.fillMaxWidth()) {
                        NotificationClickableItem(
                            icon = Icons.Default.VolumeUp,
                            title = "Notification Sound",
                            subtitle = "Default ringtone",
                            onClick = { /* Handle ringtone picker */ }
                        )
                        NotificationDivider()
                        NotificationClickableItem(
                            icon = Icons.Default.Vibration,
                            title = "Vibrate",
                            subtitle = "Enabled for important alerts",
                            onClick = { /* Handle vibration settings */ }
                        )
                    }
                }
                Spacer(modifier = Modifier.height(20.dp))
            }
        }
    }
}

@Composable
fun NotificationSwitchItem(
    icon: ImageVector,
    title: String,
    subtitle: String,
    checked: Boolean,
    onCheckedChange: (Boolean) -> Unit
) {
    Row(
        modifier = Modifier
            .fillMaxWidth()
            .padding(horizontal = 16.dp, vertical = 12.dp),
        horizontalArrangement = Arrangement.SpaceBetween,
        verticalAlignment = Alignment.CenterVertically
    ) {
        Row(
            verticalAlignment = Alignment.CenterVertically,
            modifier = Modifier.weight(1f)
        ) {
            Box(
                modifier = Modifier
                    .size(40.dp)
                    .clip(CircleShape)
                    .background(Color(0xFF3B59FF).copy(alpha = 0.1f)),
                contentAlignment = Alignment.Center
            ) {
                Icon(
                    imageVector = icon,
                    contentDescription = null,
                    tint = Color(0xFF3B59FF),
                    modifier = Modifier.size(20.dp)
                )
            }
            Spacer(modifier = Modifier.width(14.dp))
            Column {
                Text(
                    text = title,
                    fontSize = 14.sp,
                    fontWeight = FontWeight.Medium,
                    color = Color(0xFF1E1E24)
                )
                Spacer(modifier = Modifier.height(2.dp))
                Text(
                    text = subtitle,
                    fontSize = 11.5.sp,
                    color = Color.Gray
                )
            }
        }
        Switch(
            checked = checked,
            onCheckedChange = onCheckedChange,
            colors = SwitchDefaults.colors(
                checkedThumbColor = Color.White,
                checkedTrackColor = Color(0xFF3B59FF)
            )
        )
    }
}

